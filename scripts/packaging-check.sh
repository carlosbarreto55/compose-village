#!/usr/bin/env bash
# Packaging check (spike tasks 8.2-8.3): builds the macOS distributable and DMG, measures the
# compiler's share of them, and runs the bundled app's --selftest. Writes docs/spike/packaging.md.
#
# The "without compiler" variant is the same .app minus the compiler-only jars. Both variants are
# compressed with the same `hdiutil create -format UDZO` call, so their difference is the compiler's
# compressed cost. The runtime is the same in both: of the modules beyond Compose's defaults, the
# guard needs java.management/jdk.management, and the rest are measured separately as an upper bound.
#
# Usage: scripts/packaging-check.sh   (macOS, JDK 17)
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT=$PWD
JAVA_HOME=${JAVA_HOME:-$(/usr/libexec/java_home -v 17)}
BIN=app/build/compose/binaries/main
APP=$BIN/app/ComposeVillage.app
OUT=docs/spike/packaging.md
WORK=app/build/packaging-check
# Jars only the embedded compiler pipeline needs: the compiler and its own dependencies, the Compose
# plugin, ASM, and the `compiler` module. Everything else is also needed by a game without it.
COMPILER_JARS='^(kotlin-compiler-embeddable|kotlin-compose-compiler-plugin-embeddable|kotlin-build-tools-api|kotlin-daemon-embeddable|kotlin-script-runtime|kotlin-reflect|asm|asm-tree|asm-util|asm-analysis|compiler)-[^/]*\.jar$'
# The modules the Compose Gradle plugin always puts in the runtime.
DEFAULT_MODULES=java.base,java.desktop,java.logging,jdk.crypto.ec
# Modules jdeps suggests but the bundle does not ship (see app/build.gradle.kts), measured to show the saving.
UNSHIPPED_MODULES=java.scripting,jdk.compiler

./gradlew -q :app:packageDmg

rm -rf "$WORK" && mkdir -p "$WORK"
kb() { du -sk "$1" | cut -f1; }
mb() { awk -v k="$1" 'BEGIN { printf "%.1f MB", k / 1024 }'; }
bytes_mb() { awk -v b="$1" 'BEGIN { printf "%.1f MB", b / 1048576 }'; }

# --- the bundle as built ---
DMG=$(ls "$BIN"/dmg/*.dmg)
APP_KB=$(kb "$APP")
RUNTIME_KB=$(kb "$APP/Contents/runtime")
JARS_KB=$(kb "$APP/Contents/app")
DMG_BYTES=$(stat -f %z "$DMG")
MODULES=$(sed -n 's/^MODULES="\(.*\)"/\1/p' "$APP/Contents/runtime/Contents/Home/release")

COMPILER_JAR_ROWS=""
COMPILER_JARS_BYTES=0
for jar in $(ls "$APP/Contents/app" | grep -E "$COMPILER_JARS"); do
  size=$(stat -f %z "$APP/Contents/app/$jar")
  COMPILER_JARS_BYTES=$((COMPILER_JARS_BYTES + size))
  COMPILER_JAR_ROWS+="| \`$jar\` | $(bytes_mb "$size") |"$'\n'
done

# --- the same bundle without the compiler ---
cp -R "$APP" "$WORK/full.app"
cp -R "$APP" "$WORK/stripped.app"
ls "$WORK/stripped.app/Contents/app" | grep -E "$COMPILER_JARS" | while read -r jar; do rm "$WORK/stripped.app/Contents/app/$jar"; done
jlink_kb() { # modules -> size of a runtime jlinked like the bundle's
  local dir=$WORK/runtime-$RANDOM
  "$JAVA_HOME/bin/jlink" --add-modules "$1" --strip-debug --no-header-files --no-man-pages --strip-native-commands --output "$dir"
  kb "$dir"
}
DEFAULT_RUNTIME_KB=$(jlink_kb "$DEFAULT_MODULES")
SHIPPED_RUNTIME_KB=$(jlink_kb "$(tr ' ' ',' <<<"$MODULES")")
WITH_UNSHIPPED_KB=$(jlink_kb "$(tr ' ' ',' <<<"$MODULES"),$UNSHIPPED_MODULES")
STRIPPED_KB=$(kb "$WORK/stripped.app")
STRIPPED_RUNTIME_KB=$(kb "$WORK/stripped.app/Contents/runtime")
STRIPPED_JARS_KB=$(kb "$WORK/stripped.app/Contents/app")

udzo() { hdiutil create -quiet -format UDZO -srcfolder "$1" -volname ComposeVillage "$2" && stat -f %z "$2"; }
FULL_UDZO=$(udzo "$WORK/full.app" "$WORK/full.dmg")
STRIPPED_UDZO=$(udzo "$WORK/stripped.app" "$WORK/stripped.dmg")

# --- bundled self-test, with an empty environment so no JAVA_HOME or system JDK can help ---
START=$(perl -MTime::HiRes=time -e 'printf "%d", time * 1000')
set +e
SELFTEST=$(env -i HOME="$HOME" "$APP/Contents/MacOS/ComposeVillage" --selftest 2>&1)
SELFTEST_EXIT=$?
set -e
SELFTEST_MS=$(( $(perl -MTime::HiRes=time -e 'printf "%d", time * 1000') - START ))
BUNDLED_HOME="$ROOT/$APP/Contents/runtime/Contents/Home"
if grep -qF "compiler JDK home = $BUNDLED_HOME" <<<"$SELFTEST"; then JDK_HOME_OK=yes; else JDK_HOME_OK=NO; fi

cat >"$OUT" <<EOF
# Packaging check

Generated by \`scripts/packaging-check.sh\` on $(date '+%Y-%m-%d %H:%M') (git $(git describe --always --dirty)). Do not edit by hand: re-run the script.
Built with \`./gradlew :app:packageDmg\` on $(sw_vers -productName) $(sw_vers -productVersion) ($(uname -m)), JDK $(sed -n 's/^JAVA_VERSION="\(.*\)"/\1/p' "$JAVA_HOME/release") from \`$JAVA_HOME\`.

## Bundled self-test

| Item | Value |
| --- | --- |
| Command | \`env -i HOME=\$HOME ComposeVillage.app/Contents/MacOS/ComposeVillage --selftest\` |
| Exit status | $SELFTEST_EXIT ($( [ "$SELFTEST_EXIT" = 0 ] && echo PASS || echo '**FAIL**' )) |
| Wall time (launch to exit) | $SELFTEST_MS ms |
| Compiler JDK home is the bundled runtime | $JDK_HOME_OK |

\`\`\`
$(sed "s|$ROOT/||g" <<<"$SELFTEST")
\`\`\`

## Sizes

| | With the compiler (as shipped) | Without the compiler | Compiler's share |
| --- | --- | --- | --- |
| \`.app\` on disk | $(mb "$APP_KB") | $(mb "$STRIPPED_KB") | $(mb $((APP_KB - STRIPPED_KB))) |
| ↳ jars and native libraries (\`Contents/app\`) | $(mb "$JARS_KB") | $(mb "$STRIPPED_JARS_KB") | $(mb $((JARS_KB - STRIPPED_JARS_KB))) |
| ↳ Java runtime (\`Contents/runtime\`) | $(mb "$RUNTIME_KB") | $(mb "$STRIPPED_RUNTIME_KB") | see below |
| DMG, \`hdiutil create -format UDZO\` | $(bytes_mb "$FULL_UDZO") | $(bytes_mb "$STRIPPED_UDZO") | $(bytes_mb $((FULL_UDZO - STRIPPED_UDZO))) |
| DMG from \`packageDmg\` (jpackage) | $(bytes_mb "$DMG_BYTES") | not built | |

Runtime modules shipped: \`$MODULES\`. The runtime is the same in both variants. Its modules beyond Compose's
defaults (\`$DEFAULT_MODULES\`) add $(mb $((SHIPPED_RUNTIME_KB - DEFAULT_RUNTIME_KB))) to a jlinked runtime: an upper bound
for the compiler's runtime share, since the guard needs \`java.management\`/\`jdk.management\` either way.
\`suggestRuntimeModules\` also lists \`${UNSHIPPED_MODULES/,/, }\`; they are not shipped (the self-test passes without
them) and would add $(mb $((WITH_UNSHIPPED_KB - SHIPPED_RUNTIME_KB))).

Compiler-only jars ($(bytes_mb "$COMPILER_JARS_BYTES") uncompressed):

| Jar | Size |
| --- | --- |
$COMPILER_JAR_ROWS
EOF

echo "wrote $OUT"
[ "$SELFTEST_EXIT" = 0 ] && [ "$JDK_HOME_OK" = yes ]
