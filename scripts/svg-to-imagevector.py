#!/usr/bin/env python3
"""Converts the villager profession glyphs (design-docs/cozy/icons/*.svg) to Compose ImageVectors
(cozy-level-screen design D3) and writes app/src/main/kotlin/village/app/ui/icons/VillagerIcons.kt.

The glyphs use only <path>, <circle> and <rect> stroked in currentColor, so each element becomes one
path: circles as two arcs, rounded rects as lines and arcs. Strokes are drawn in black and tinted at
the call site. The embedded <metadata> block is dropped. Run again after changing an icon:

    python3 scripts/svg-to-imagevector.py
"""
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, "design-docs", "cozy", "icons")
OUT = os.path.join(ROOT, "app", "src", "main", "kotlin", "village", "app", "ui", "icons", "VillagerIcons.kt")
SVG = "{http://www.w3.org/2000/svg}"


def num(v):
    return f"{float(v):g}"


def circle(e):
    cx, cy, r = (float(e.get(k)) for k in ("cx", "cy", "r"))
    return f"M{num(cx - r)} {num(cy)} A{num(r)} {num(r)} 0 1 0 {num(cx + r)} {num(cy)} A{num(r)} {num(r)} 0 1 0 {num(cx - r)} {num(cy)} Z"


def rect(e):
    x, y, w, h = (float(e.get(k)) for k in ("x", "y", "width", "height"))
    r = float(e.get("rx", 0))
    if r == 0:
        return f"M{num(x)} {num(y)} H{num(x + w)} V{num(y + h)} H{num(x)} Z"
    a = f"A{num(r)} {num(r)} 0 0 1"
    return (f"M{num(x + r)} {num(y)} H{num(x + w - r)} {a} {num(x + w)} {num(y + r)} V{num(y + h - r)} "
            f"{a} {num(x + w - r)} {num(y + h)} H{num(x + r)} {a} {num(x)} {num(y + h - r)} V{num(y + r)} {a} {num(x + r)} {num(y)} Z")


def glyph(path):
    text = re.sub(r"<metadata>.*?</metadata>", "", open(path, encoding="utf-8").read(), flags=re.S)
    root = ET.fromstring(text)
    width = root.get("stroke-width", "2")
    parts = []
    for e in root:
        tag = e.tag.replace(SVG, "")
        d = {"path": lambda e: e.get("d"), "circle": circle, "rect": rect}[tag](e)
        parts.append((d, e.get("fill") == "currentColor"))
    return width, parts


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(p.capitalize() for p in rest)


def main():
    names = sorted(f[:-4] for f in os.listdir(ICONS) if f.endswith(".svg"))
    out = [
        "package village.app.ui.icons",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.StrokeCap",
        "import androidx.compose.ui.graphics.StrokeJoin",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.addPathNodes",
        "import androidx.compose.ui.unit.dp",
        "",
        "// Generated by scripts/svg-to-imagevector.py from design-docs/cozy/icons. Do not edit by hand.",
        "",
        "/** The villager profession glyphs: 24 x 24, stroked in black, to be tinted at the call site. */",
        "object VillagerIcons {",
    ]
    for name in names:
        width, parts = glyph(os.path.join(ICONS, name + ".svg"))
        out.append(f"    val {camel(name)}: ImageVector by lazy {{")
        out.append(f"        glyph(\"{name}\", {num(width)}f,")
        for d, filled in parts:
            out.append(f"            \"{d}\" to {'true' if filled else 'false'},")
        out.append("        )")
        out.append("    }")
        out.append("")
    out += [
        "    /** One stroked path per (path data, filled) pair; filled paths are also filled, as dots are. */",
        "    private fun glyph(name: String, strokeWidth: Float, vararg paths: Pair<String, Boolean>): ImageVector =",
        "        ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {",
        "            for ((d, filled) in paths) {",
        "                addPath(",
        "                    addPathNodes(d), fill = if (filled) SolidColor(Color.Black) else null,",
        "                    stroke = SolidColor(Color.Black), strokeLineWidth = strokeWidth,",
        "                    strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round,",
        "                )",
        "            }",
        "        }.build()",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"wrote {len(names)} glyphs to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
