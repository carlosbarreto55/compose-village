package village.app.spike

import java.io.File
import java.time.LocalDateTime
import java.time.format.DateTimeFormatter

/** The spike's five success criteria (design.md, Goals). Every check names the criteria it backs. */
internal enum class Criterion(val title: String) {
    WARM_COMPILE("Warm compile under 2 s for a ~30-line composable"),
    RENDERED("Player UI renders in the game window"),
    ERROR_LINES("Errors point at the correct lines"),
    SURVIVES_CRASHES("The game survives runtime exceptions and runaway code"),
    NO_LEAKS("No memory growth over 100+ reloads"),
}

internal class Check(val name: String, val pass: Boolean, val detail: String, val criteria: Set<Criterion>)

/** One part of the report: free markdown followed by a table of its checks. */
internal class Section(val title: String) {
    val checks = mutableListOf<Check>()
    private val body = StringBuilder()

    /** Records and prints a check; [detail] is shown in the report, and also on the console when it fails. */
    fun check(name: String, pass: Boolean, vararg criteria: Criterion, detail: () -> String = { "" }): Boolean {
        val text = runCatching(detail).getOrElse { "detail failed: $it" }
        checks += Check(name, pass, text, criteria.toSet())
        println("${if (pass) "PASS" else "FAIL"} $name")
        if (!pass && text.isNotBlank()) println(text.prependIndent("    "))
        return pass
    }

    fun text(markdown: String) {
        body.appendLine(markdown.trimIndent()).appendLine()
    }

    fun table(header: List<String>, rows: List<List<Any?>>) {
        body.appendLine(markdownTable(header, rows)).appendLine()
    }

    fun markdown(): String = buildString {
        appendLine("## $title").appendLine()
        append(body)
        if (checks.isNotEmpty()) {
            appendLine(markdownTable(listOf("Check", "Result", "Detail"), checks.map { listOf(it.name, if (it.pass) "PASS" else "**FAIL**", it.detail) }))
            appendLine()
        }
    }
}

/**
 * Collects sections and writes `results.md` plus CSV files into [outDir]. A section that throws is
 * recorded as a failed check against the criteria it was meant to back, so a crash in the harness
 * can never turn into a PASS.
 */
internal class Report(val outDir: File) {
    private val sections = mutableListOf<Section>()
    private val evidence = mutableMapOf<Criterion, String>()
    private val csvFiles = mutableListOf<String>()

    val failed get() = sections.any { s -> s.checks.any { !it.pass } }

    fun section(title: String, vararg criteria: Criterion, block: Section.() -> Unit) {
        println("\n== $title")
        val section = Section(title)
        sections += section
        try {
            section.block()
        } catch (t: Throwable) {
            section.check("$title ran to completion", false, *criteria) { t.stackTraceToString().lines().take(12).joinToString("\n") }
        }
    }

    /** The one-line evidence shown next to [criterion]'s verdict, instead of a check count. */
    fun evidence(criterion: Criterion, text: String) {
        evidence[criterion] = text
    }

    fun csv(name: String, header: List<String>, rows: List<List<Any?>>) {
        outDir.mkdirs()
        File(outDir, name).writeText((listOf(header) + rows).joinToString("\n", postfix = "\n") { row -> row.joinToString(",") { csvCell(it) } })
        csvFiles += name
    }

    fun write(environment: List<List<Any?>>): File {
        outDir.mkdirs()
        val checks = sections.flatMap { it.checks }
        val file = File(outDir, "results.md")
        file.writeText(buildString {
            appendLine("# Spike harness results").appendLine()
            appendLine("Generated by `./gradlew :app:spike` on ${LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm"))}. ")
            appendLine("Do not edit by hand: re-run the harness. Raw series: ${csvFiles.joinToString { "[`$it`]($it)" }.ifEmpty { "none" }}. ")
            appendLine("The written spike report with the recommendation is [`report.md`](report.md).").appendLine()
            appendLine("## Success criteria").appendLine()
            appendLine(markdownTable(listOf("Criterion", "Verdict", "Evidence"), Criterion.entries.map { c ->
                val backing = checks.filter { c in it.criteria }
                val verdict = when {
                    backing.isEmpty() -> "NOT RUN"
                    backing.all { it.pass } -> "PASS"
                    else -> "**FAIL**"
                }
                val counts = "${backing.count { it.pass }}/${backing.size} checks passed"
                listOf(c.title, verdict, evidence[c]?.let { "$it ($counts)" } ?: counts)
            }))
            appendLine()
            appendLine("## Environment").appendLine()
            appendLine(markdownTable(listOf("Item", "Value"), environment)).appendLine()
            sections.forEach { append(it.markdown()) }
        })
        return file
    }

    private fun csvCell(value: Any?): String {
        val s = value?.toString() ?: ""
        return if (s.any { it == ',' || it == '"' || it == '\n' }) "\"" + s.replace("\"", "\"\"") + "\"" else s
    }
}

internal fun markdownTable(header: List<String>, rows: List<List<Any?>>): String = buildString {
    fun cell(value: Any?) = (value?.toString() ?: "").replace("|", "\\|").replace("\n", "<br>")
    appendLine(header.joinToString(" | ", "| ", " |"))
    appendLine(header.joinToString(" | ", "| ", " |") { "---" })
    rows.forEach { row -> appendLine(row.joinToString(" | ", "| ", " |") { cell(it) }) }
}.trimEnd()
